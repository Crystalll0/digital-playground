U=125; ADV=6*U; asc=8*U
names=['.notdef','space']; cmap={32:'space'}; glyphs={}
def pen_for(rows):
    p=TTGlyphPen(None)
    for r,row in enumerate(rows):
        for c,ch in enumerate(row):
            if ch=='1':
                x0=c*U; y1=(7-r)*U; y0=y1-U
                p.moveTo((x0,y0)); p.lineTo((x0,y1)); p.lineTo((x0+U,y1)); p.lineTo((x0+U,y0)); p.closePath()
    return p.glyph()
glyphs['.notdef']=pen_for(["11111","10001","10001","10001","10001","10001","11111"])
glyphs['space']=TTGlyphPen(None).glyph()
for i,(ch,rows) in enumerate(G.items()):
    n='g%d'%i; names.append(n); glyphs[n]=pen_for(rows); cmap[ord(ch)]=n
    if 'A'<=ch<='Z': cmap[ord(ch.lower())]=n
fb=FontBuilder(1000,isTTF=True); fb.setupGlyphOrder(names); fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs); fb.setupHorizontalMetrics({n:(ADV,0) for n in names})
fb.setupHorizontalHeader(ascent=asc,descent=-U*2)
fb.setupNameTable({'familyName':'Crunch Pixel','styleName':'Regular'})
fb.setupOS2(sTypoAscender=asc,sTypoDescender=-U*2,usWinAscent=asc,usWinDescent=U*2); fb.setupPost()
